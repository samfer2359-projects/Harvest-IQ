#This function takes the path of an image, preprocesses it, and predicts which class (disease) the image belongs to.
def prediction(path):

  img = load_img(path , target_size= (256,256))

  i = img_to_array(img)

  im = preprocess_input(i)

  img = np.expand_dims(im, axis= 0)

  #print(img.shape)

  pred = np.argmax(model.predict(img))

  print(f" the image belogs to  { ref[pred] }")

