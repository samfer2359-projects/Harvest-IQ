import os
os.listdir("plantdisease/PlantVillage")

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import os

import keras

from  tensorflow.keras.preprocessing.image import ImageDataGenerator , img_to_array , load_img
from keras.applications.vgg19 import VGG19 , preprocess_input , decode_predictions

#EDA exploratory data analysis
len(os.listdir("plantdisease/PlantVillage"))

#Prepare images by applying random transformations
train_datagen = ImageDataGenerator(zoom_range= 0.5, shear_range= 0.3, horizontal_flip=True, preprocessing_function= preprocess_input)
val_datagen = ImageDataGenerator(preprocessing_function= preprocess_input)

#loads images from the folder and prepare them
train = train_datagen.flow_from_directory(directory="plantdisease/PlantVillage", target_size=(256,256), batch_size=32)
val = val_datagen.flow_from_directory(directory="plantdisease/PlantVillage", target_size=(256,256), batch_size=32)

#batches of image and labels
t_img, label = next(train)

t_img.shape

def plotImage(img_arr, label):
  for im , l in zip(img_arr, label):
    plt.figure(figsize=(5,5))
    plt.imshow(im)
    plt.show()

plotImage(t_img[:3],label[:3])

from keras.layers import Dense, Flatten
from keras.models import Model

#VGG19: A pre-trained image classification model
base_model = VGG19(input_shape=(256,256,3), include_top= False)
#include_top=False means it doesn't include the final classification layer (we will add our own).

#we don't want to train those layers, just use them as feature extractors.
for layer in base_model.layers:
  layer.trainable = False

base_model.summary()

X = Flatten()(base_model.output)

X = Dense(units= 15, activation= 'softmax')(X)

#create model
model = Model(base_model.input, X)

model.compile(optimizer= 'adam' , loss= keras.losses.categorical_crossentropy , metrics= ['accuracy'])

from keras.callbacks import ModelCheckpoint, EarlyStopping

#early stopping
es= EarlyStopping(monitor= 'val_accuracy', min_delta= 0.01, patience= 3, verbose= 1)

#model check point
mc = ModelCheckpoint(filepath= "best_plant_disease_model.h5", monitor= 'val_accuracy', verbose= 1, save_best_only= True)

cb = [es, mc]

total_no_of_images = len(train.filenames) # train.batch_size
print(total_no_of_images)
print(train.batch_size)
steps_per_epoch = np.ceil(total_no_of_images/train.batch_size)
print(total_no_of_images/train.batch_size)
print(steps_per_epoch)

#This trains the model with the training data and validates it with the validation data
his = model.fit(train, steps_per_epoch= int(steps_per_epoch), epochs= 50, verbose= 1, callbacks= cb, validation_data= val, validation_steps= int(steps_per_epoch))

h = his.history
h.keys()

plt.plot(h['accuracy'])
plt.plot(h['val_accuracy'] , c = "red")
plt.title("acc vs v-acc")
plt.show()

